//! The LaTeX vocabulary command completion offers when nothing better
//! answers: common commands with what each means (and the template a pick
//! inserts, the caret in its first empty `{}`), and common environments.
//!
//! Ported entry for entry from the Tauri app's
//! `src/editor/latex/latex-vocabulary.ts` and the extra entries of
//! `latex-command-completions.ts`, the shared vocabulary first and a name
//! listed twice kept at its first place. The details are the English source
//! strings the Tauri app's catalog is keyed by, ready for `lattice-i18n`.

/// One command or environment.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Entry {
    pub name: &'static str,
    pub detail: &'static str,
    /// What a pick inserts, when more than the name.
    pub template: Option<&'static str>,
    /// The package that defines it, shown after the detail.
    pub package: Option<&'static str>,
    /// Offered only inside maths.
    pub math: bool,
}

const fn e(name: &'static str, detail: &'static str) -> Entry {
    Entry {
        name,
        detail,
        template: None,
        package: None,
        math: false,
    }
}

impl Entry {
    const fn template(mut self, template: &'static str) -> Self {
        self.template = Some(template);
        self
    }

    const fn package(mut self, package: &'static str) -> Self {
        self.package = Some(package);
        self
    }

    const fn math(mut self) -> Self {
        self.math = true;
        self
    }

    /// The detail as the menu shows it: with its package in parentheses.
    pub fn detail_text(&self) -> String {
        match self.package {
            Some(package) => format!("{} ({package})", self.detail),
            None => self.detail.to_string(),
        }
    }
}

