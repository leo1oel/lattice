//! The precomposed letters BibTeX's accent commands make (`\"o` is "ö"):
//! a Latin letter and the combining mark of an accent, and the one character
//! Unicode composes them into (NFC), for the pairs that have one. Generated
//! from Python's `unicodedata.normalize("NFC", letter + mark)` over the
//! ASCII letters, dotless i and dotless j, and the fifteen marks the accent
//! commands put; a pair with no precomposed form keeps its combining mark.

/// The precomposed form of `letter` followed by `mark`, if Unicode has one.
pub(super) fn compose(letter: char, mark: char) -> Option<char> {
    PAIRS
        .binary_search_by(|(base, combining, _)| (*base, *combining).cmp(&(letter, mark)))
        .ok()
        .map(|at| PAIRS[at].2)
}

