#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_composes() {
        assert!(PAIRS.windows(2).all(|pair| (pair[0].0, pair[0].1) < (pair[1].0, pair[1].1)));
        assert_eq!(compose('o', '\u{0308}'), Some('ö'));
        assert_eq!(compose('c', '\u{0327}'), Some('ç'));
        assert_eq!(compose('q', '\u{0308}'), None);
    }
}
