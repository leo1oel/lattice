#!/usr/bin/env node
/**
 * Deterministically generate a performance-fixture project for the probes in
 * src/platform/perf-probe.ts (see docs/performance.md for the measurement playbook).
 *
 * Layout (all content derived from fixed seeds — two runs produce identical
 * bytes, so before/after measurements compare the same document):
 *   large.md      ~2 MB, ~5000 top-level blocks (paragraphs, headings, tables,
 *                 inline/display math, code fences) — the long-Markdown case.
 *   main.tex      root document \include-ing chapters/chNN.tex
 *   chapters/     8 chapters, ~1 MB of TeX total
 *   notes/        200 small .md files — makes scan_files/poll cost visible.
 *
 * Usage: node scripts/gen-perf-fixture.mjs <target-dir>
 * The target must not already contain a fixture (refuses to overwrite
 * anything but its own previous output, keyed on the marker file).
 */
import { mkdirSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";

const target = process.argv[2];
if (!target) {
  console.error("usage: node scripts/gen-perf-fixture.mjs <target-dir>");
  process.exit(1);
}
const MARKER = path.join(target, ".lattice-perf-fixture");
if (existsSync(target) && !existsSync(MARKER) && readdirSync(target).length > 0) {
  console.error(`refusing to write into ${target}: non-empty and not a previous fixture output`);
  process.exit(1);
}

// Small deterministic PRNG (mulberry32) — no Math.random so the fixture is
// byte-stable across runs and machines.
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const WORDS = (
  "lattice performance viewport incremental parse render layout decoration " +
  "transaction editor document markdown latex snapshot durable collab pool " +
  "anchor heading paragraph fixture deterministic measure keystroke switch"
).split(" ");

function sentence(rand, words) {
  const parts = [];
  for (let i = 0; i < words; i += 1) parts.push(WORDS[Math.floor(rand() * WORDS.length)]);
  const s = parts.join(" ");
  return s.charAt(0).toUpperCase() + s.slice(1) + ".";
}

function paragraph(rand) {
  const sentences = 3 + Math.floor(rand() * 4);
  return Array.from({ length: sentences }, () => sentence(rand, 8 + Math.floor(rand() * 12))).join(" ");
}

function mdBlock(rand, index) {
  const kind = index % 25;
  if (kind === 0) return `## Section ${Math.floor(index / 25) + 1}: ${sentence(rand, 4)}`;
  if (kind === 7) {
    return [
      "| Metric | Before | After |",
      "| --- | --- | --- |",
      `| keystroke p95 | ${Math.floor(rand() * 90)} ms | ${Math.floor(rand() * 20)} ms |`,
      `| switch | ${Math.floor(rand() * 900)} ms | ${Math.floor(rand() * 200)} ms |`,
    ].join("\n");
  }
  if (kind === 12) {
    return ["```ts", `export function probe${index}(): number {`, `  return ${index} * 2;`, "}", "```"].join("\n");
  }
  if (kind === 18) return `$$\\sum_{i=0}^{${index}} x_i^2 = \\frac{${index}}{n}$$`;
  if (kind === 21) return `- ${sentence(rand, 6)}\n- ${sentence(rand, 6)}\n- ${sentence(rand, 6)}`;
  const math = kind === 4 ? ` Inline $x_{${index}} = y^2$ math.` : "";
  return paragraph(rand) + math;
}

mkdirSync(path.join(target, "chapters"), { recursive: true });
mkdirSync(path.join(target, "notes"), { recursive: true });
writeFileSync(MARKER, "generated by scripts/gen-perf-fixture.mjs\n");

// large.md — grow until ~2 MB.
{
  const rand = rng(0x1a77);
  const blocks = [`# Lattice perf fixture`, ""];
  let size = 0;
  let index = 0;
  while (size < 2_000_000) {
    const block = mdBlock(rand, index);
    blocks.push(block, "");
    size += block.length + 2;
    index += 1;
  }
  writeFileSync(path.join(target, "large.md"), blocks.join("\n"));
  console.log(`large.md: ${(size / 1e6).toFixed(2)} MB, ${index} blocks`);
}

// TeX tree — main.tex + 8 chapters (~1 MB total).
{
  const chapters = [];
  for (let c = 1; c <= 8; c += 1) {
    const rand = rng(1000 + c);
    const lines = [`\\chapter{Chapter ${c}}`, `\\label{ch:${c}}`, ""];
    let size = 0;
    let section = 0;
    while (size < 125_000) {
      section += 1;
      lines.push(`\\section{Section ${c}.${section}}`, "");
      for (let p = 0; p < 4; p += 1) {
        const text = paragraph(rand);
        lines.push(text, "");
        size += text.length;
      }
      lines.push(`\\begin{equation}\\label{eq:${c}-${section}} x_{${section}} = \\sum_i y_i \\end{equation}`, "");
    }
    const name = `chapters/ch${String(c).padStart(2, "0")}.tex`;
    writeFileSync(path.join(target, name), lines.join("\n"));
    chapters.push(name.replace(/\.tex$/, ""));
  }
  const main = [
    "\\documentclass{book}",
    "\\usepackage{amsmath}",
    "\\newcommand{\\lattice}{\\textsc{Lattice}}",
    "\\begin{document}",
    ...chapters.map((chapter) => `\\include{${chapter}}`),
    "\\end{document}",
  ];
  writeFileSync(path.join(target, "main.tex"), main.join("\n"));
  console.log(`main.tex + ${chapters.length} chapters`);
}

// notes/ — 200 small markdown files for scan/poll pressure.
for (let n = 0; n < 200; n += 1) {
  const rand = rng(9000 + n);
  const lines = [`# Note ${n}`, "", paragraph(rand), "", `- TODO: ${sentence(rand, 5)}`];
  writeFileSync(path.join(target, `notes/note-${String(n).padStart(3, "0")}.md`), lines.join("\n"));
}
console.log("notes/: 200 files");
console.log(`fixture ready at ${target}`);
