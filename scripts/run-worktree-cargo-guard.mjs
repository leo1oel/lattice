#!/usr/bin/env node
/**
 * Keeps plain cargo from compiling in a no-mistakes run worktree.
 *
 * Validation agents were told to compile only through scripts/gpui-build.mjs,
 * but some still ran `cargo test` or `cargo clippy` in the run worktree, and
 * each such worktree grew a cold 8-10 GB gpui/target (2-3 GB src-tauri/target),
 * four at a time, until the machine's disk ran out. Pointing every checkout at
 * one shared CARGO_TARGET_DIR is not a fix: Cargo decides freshness by mtime
 * and names path crates relative to the workspace root, so a worktree whose
 * files were checked out before another worktree's build reuses that build's
 * artifacts and silently tests the other worktree's code. gpui-build.mjs is
 * safe because its mirror gives every changed file a new mtime.
 *
 *   node scripts/run-worktree-cargo-guard.mjs install
 *     `.no-mistakes.yaml`'s prepare command runs this in each run worktree. It
 *     writes the worktree's git-ignored .cargo/config.toml, whose
 *     `build.rustc-wrapper` is scripts/run-worktree-rustc-wrapper.sh. Skipped
 *     under CI and on Windows; an existing .cargo/config.toml it did not write
 *     is left alone. Being ignored, the file never reaches the shared build
 *     tree gpui-build.mjs mirrors into, so builds there are unaffected; lane
 *     worktrees and the primary checkout never run the prepare command.
 *
 *   node scripts/run-worktree-cargo-guard.mjs refuse <rustc> <args...>
 *     What the wrapper runs. For a cargo subcommand that compiles it exits 1
 *     with the same command through gpui-build.mjs (Cargo prints that under
 *     its own "process didn't exit successfully" error); for any other
 *     subcommand (`metadata`, `tree`) it runs rustc as asked.
 *
 * To lift the guard: LATTICE_ALLOW_LOCAL_CARGO=1 for one command, or delete
 * .cargo/config.toml in the worktree.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gpuiBuildCommand } from "./lib/run-worktree-cargo-guard.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const wrapper = path.join(repo, "scripts", "run-worktree-rustc-wrapper.sh");
const MARKER = "# Generated by scripts/run-worktree-cargo-guard.mjs";

function install() {
  if (process.env.CI) return console.log("run-worktree-cargo-guard: CI is set; not installing");
  if (process.platform === "win32") return console.log("run-worktree-cargo-guard: not installed on Windows");
  const config = path.join(repo, ".cargo", "config.toml");
  if (existsSync(config) && !readFileSync(config, "utf8").startsWith(MARKER)) {
    return console.warn(`run-worktree-cargo-guard: ${config} exists and was not written by this script; leaving it, so plain cargo is not guarded here`);
  }
  mkdirSync(path.dirname(config), { recursive: true });
  chmodSync(wrapper, 0o755);
  writeFileSync(
    config,
    `${MARKER} for this no-mistakes run worktree
# (.no-mistakes.yaml, commands.prepare). It is git-ignored. A compiling cargo
# command here fails at once with the same command through
# scripts/gpui-build.mjs; LATTICE_ALLOW_LOCAL_CARGO=1 lifts that for one
# command, and deleting this file lifts it for good.
[build]
rustc-wrapper = ${JSON.stringify(wrapper)}
`,
  );
  console.log(`run-worktree-cargo-guard: plain cargo that compiles is refused in ${repo} (${config})`);
}

/** The outermost cargo above this process: `cargo clippy` runs `cargo-clippy`, which runs `cargo check`. */
function outermostCargo() {
  let pid = process.ppid;
  let found;
  for (let depth = 0; depth < 8 && pid > 1; depth++) {
    const line = execFileSync("ps", ["-o", "ppid=,args=", "-p", String(pid)], { encoding: "utf8" }).trim();
    const [, parent, args] = line.match(/^(\d+)\s+(.*)$/) ?? [];
    if (!args) break;
    const [program, ...rest] = args.split(/\s+/);
    if (!/^cargo(-clippy)?$/.test(path.basename(program))) break;
    // Cargo starts `cargo-clippy clippy <args>`; keep the subcommand either way.
    found = path.basename(program) === "cargo-clippy" && rest[0] !== "clippy" ? ["clippy", ...rest] : rest;
    pid = Number(parent);
  }
  return found;
}

/** The directory of the Cargo.toml cargo picks from `dir`, relative to the checkout, or undefined. */
function nearestManifest(dir) {
  for (let current = dir; current.startsWith(repo); current = path.dirname(current)) {
    if (existsSync(path.join(current, "Cargo.toml"))) return path.relative(repo, current).split(path.sep).join("/");
    if (current === repo) break;
  }
  return undefined;
}

function refuse(rustc) {
  let suggestion;
  try {
    const args = outermostCargo();
    const cwd = process.cwd();
    if (args) suggestion = gpuiBuildCommand(args, path.relative(repo, cwd).split(path.sep).join("/"), nearestManifest(cwd));
  } catch {
    // ps unavailable or unexpected output: fall back to the generic advice.
  }
  if (suggestion && !suggestion.compiles) {
    const result = spawnSync(rustc[0], rustc.slice(1), { stdio: "inherit" });
    process.exit(result.status ?? 1);
  }
  const command = suggestion?.command ?? "node scripts/gpui-build.mjs -- <the same cargo arguments>";
  console.error(
    [
      `lattice: plain cargo that compiles is refused in this no-mistakes run worktree (${repo}),`,
      "where it would write a cold multi-GB gpui/target or src-tauri/target and fill the machine's disk.",
      "Run it through the machine's shared, warm build tree instead, from the worktree root, in the foreground:",
      "",
      `    ${command}`,
      "",
      ...(suggestion?.note ? [suggestion.note, ""] : []),
      "`cargo fmt` builds nothing and runs directly. Guard: scripts/run-worktree-cargo-guard.mjs (docs/agent-validation.md).",
    ].join("\n"),
  );
  process.exit(1);
}

const [mode, ...rest] = process.argv.slice(2);
if (mode === "install") install();
else if (mode === "refuse" && rest.length) refuse(rest);
else {
  console.error("usage: node scripts/run-worktree-cargo-guard.mjs install | refuse <rustc> <args...>");
  process.exit(2);
}
