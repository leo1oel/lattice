#!/usr/bin/env node
/**
 * Keeps plain cargo from compiling in a no-mistakes run worktree.
 *
 * Validation agents were told to compile only through scripts/gpui-build.mjs,
 * but some still ran `cargo test` or `cargo clippy` in the run worktree, and
 * each such worktree grew a cold 8-10 GB gpui/target (2-3 GB src-tauri/target),
 * four at a time, until the machine's disk ran out. Pointing every checkout at
 * one shared CARGO_TARGET_DIR is not a fix: Cargo decides freshness by mtime
 * and names path crates relative to the workspace root, so a worktree whose
 * files were checked out before another worktree's build reuses that build's
 * artifacts and silently tests the other worktree's code. gpui-build.mjs is
 * safe because its mirror gives every changed file a new mtime.
 *
 *   node scripts/run-worktree-cargo-guard.mjs install
 *     `.no-mistakes.yaml`'s prepare command runs this in each run worktree. It
 *     writes the worktree's git-ignored .cargo/config.toml, whose
 *     `build.rustc-wrapper` is scripts/run-worktree-rustc-wrapper.sh. Skipped
 *     under CI and on Windows; an existing .cargo/config.toml it did not write
 *     is left alone. Being ignored, the file never reaches the shared build
 *     tree gpui-build.mjs mirrors into, so builds there are unaffected; lane
 *     worktrees and the primary checkout never run the prepare command.
 *
 *     no-mistakes runs the prepare command lazily, at the start of the test
 *     step, so the review step (whose agent also applies fixes and compiles to
 *     check them) ran before any of this existed and left the 8-10 GB targets
 *     anyway. So install also writes a .cargo/config.toml one level up, in the
 *     directory that holds this repository's run worktrees
 *     (<no-mistakes home>/worktrees/<repo>/). That directory outlives each
 *     run, and Cargo reads the config files of every directory above the one
 *     it runs in, so from the first prepare on, every later run worktree is
 *     guarded from its first cargo command. Its wrapper is a copy kept beside
 *     that config, since a run worktree (and its scripts/) is deleted when the
 *     run ends; it finds the run worktree a rustc call belongs to and hands
 *     the call to that worktree's own copy of this script.
 *
 *   node scripts/run-worktree-cargo-guard.mjs refuse <rustc> <args...>
 *     What the wrappers run. For a cargo subcommand that compiles it exits 1
 *     with the same command through gpui-build.mjs (Cargo prints that under
 *     its own "process didn't exit successfully" error); for any other
 *     subcommand (`metadata`, `tree`) it runs rustc as asked.
 *
 *   node scripts/run-worktree-cargo-guard.mjs check
 *     The pipeline's test and lint commands run this first. In a run worktree
 *     it fails when gpui/target or src-tauri/target holds more than 500 MB
 *     besides the lattice-gpui binaries gpui-build.mjs copies back: a local
 *     compile leaves gigabytes, so that much means something compiled here
 *     despite the guard. Elsewhere it does nothing.
 *
 * To lift the guard: LATTICE_ALLOW_LOCAL_CARGO=1 for one command, or delete
 * .cargo/config.toml in the worktree and in the directory above it.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gpuiBuildCommand, repoLevelWrapper } from "./lib/run-worktree-cargo-guard.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const wrapper = path.join(repo, "scripts", "run-worktree-rustc-wrapper.sh");
const MARKER = "# Generated by scripts/run-worktree-cargo-guard.mjs";
const TARGET_LIMIT_MB = 500;

/**
 * The directory holding this repository's no-mistakes run worktrees, when this
 * checkout is one of them: <home>/worktrees/<repo id>/<run id>, where <home>
 * holds the daemon's state.sqlite. Undefined for any other checkout.
 */
function runWorktreesDir() {
  const runs = path.dirname(repo);
  const worktrees = path.dirname(runs);
  if (path.basename(worktrees) !== "worktrees" || !existsSync(path.join(path.dirname(worktrees), "state.sqlite"))) return undefined;
  return realpathSync(runs);
}

/** Writes `config` unless a file this script did not write is already there; returns whether it wrote. */
function writeConfig(config, body) {
  if (existsSync(config) && !readFileSync(config, "utf8").startsWith(MARKER)) {
    console.warn(`run-worktree-cargo-guard: ${config} exists and was not written by this script; leaving it, so plain cargo is not guarded there`);
    return false;
  }
  mkdirSync(path.dirname(config), { recursive: true });
  writeFileSync(config, body);
  return true;
}

function install() {
  if (process.env.CI) return console.log("run-worktree-cargo-guard: CI is set; not installing");
  if (process.platform === "win32") return console.log("run-worktree-cargo-guard: not installed on Windows");
  chmodSync(wrapper, 0o755);
  const config = path.join(repo, ".cargo", "config.toml");
  const wrote = writeConfig(
    config,
    `${MARKER} for this no-mistakes run worktree
# (.no-mistakes.yaml, commands.prepare). It is git-ignored. A compiling cargo
# command here fails at once with the same command through
# scripts/gpui-build.mjs; LATTICE_ALLOW_LOCAL_CARGO=1 lifts that for one
# command, and deleting this file and ../.cargo/config.toml lifts it for good.
[build]
rustc-wrapper = ${JSON.stringify(wrapper)}
`,
  );
  if (wrote) console.log(`run-worktree-cargo-guard: plain cargo that compiles is refused in ${repo} (${config})`);

  const runs = runWorktreesDir();
  if (!runs) return;
  const runsWrapper = path.join(runs, ".cargo", "lattice-rustc-wrapper.sh");
  const runsConfig = path.join(runs, ".cargo", "config.toml");
  const body = `${MARKER} for every no-mistakes run worktree
# of Lattice under this directory, from its first cargo command: the prepare
# command that writes each worktree's own config runs only at the test step,
# after the review step has already compiled. A compiling cargo command fails
# at once with the same command through scripts/gpui-build.mjs;
# LATTICE_ALLOW_LOCAL_CARGO=1 lifts that for one command, and deleting this
# file lifts it for good (until the next run's prepare writes it again).
[build]
rustc-wrapper = ${JSON.stringify(runsWrapper)}
`;
  if (!writeConfig(runsConfig, body)) return;
  writeFileSync(runsWrapper, repoLevelWrapper(MARKER, runs));
  chmodSync(runsWrapper, 0o755);
  console.log(`run-worktree-cargo-guard: plain cargo that compiles is refused in every run worktree under ${runs} (${runsConfig})`);
}

/** The outermost cargo above this process: `cargo clippy` runs `cargo-clippy`, which runs `cargo check`. */
function outermostCargo() {
  let pid = process.ppid;
  let found;
  for (let depth = 0; depth < 8 && pid > 1; depth++) {
    const line = execFileSync("ps", ["-o", "ppid=,args=", "-p", String(pid)], { encoding: "utf8" }).trim();
    const [, parent, args] = line.match(/^(\d+)\s+(.*)$/) ?? [];
    if (!args) break;
    const [program, ...rest] = args.split(/\s+/);
    if (!/^cargo(-clippy)?$/.test(path.basename(program))) break;
    // Cargo starts `cargo-clippy clippy <args>`; keep the subcommand either way.
    found = { pid, args: path.basename(program) === "cargo-clippy" && rest[0] !== "clippy" ? ["clippy", ...rest] : rest };
    pid = Number(parent);
  }
  return found;
}

/**
 * Where `pid` runs. Cargo runs rustc for a registry crate in that crate's
 * source directory, so this process's own cwd says nothing about where the
 * cargo command was typed.
 */
function cwdOf(pid) {
  const out = execFileSync("lsof", ["-a", "-p", String(pid), "-d", "cwd", "-Fn"], { encoding: "utf8" });
  return out.split("\n").find((line) => line.startsWith("n"))?.slice(1);
}

/** The directory of the Cargo.toml cargo picks from `dir`, relative to the checkout, or undefined. */
function nearestManifest(dir) {
  for (let current = dir; current.startsWith(repo); current = path.dirname(current)) {
    if (existsSync(path.join(current, "Cargo.toml"))) return path.relative(repo, current).split(path.sep).join("/");
    if (current === repo) break;
  }
  return undefined;
}

function refuse(rustc) {
  let suggestion;
  try {
    const cargo = outermostCargo();
    if (cargo) {
      let cwd = process.cwd();
      try {
        cwd = cwdOf(cargo.pid) ?? cwd;
      } catch {
        // lsof unavailable: the suggestion may miss a --manifest-path.
      }
      suggestion = gpuiBuildCommand(cargo.args, path.relative(repo, cwd).split(path.sep).join("/"), nearestManifest(cwd));
    }
  } catch {
    // ps unavailable or unexpected output: fall back to the generic advice.
  }
  if (suggestion && !suggestion.compiles) {
    const result = spawnSync(rustc[0], rustc.slice(1), { stdio: "inherit" });
    process.exit(result.status ?? 1);
  }
  const command = suggestion?.command ?? "node scripts/gpui-build.mjs -- <the same cargo arguments>";
  console.error(
    [
      `lattice: plain cargo that compiles is refused in this no-mistakes run worktree (${repo}),`,
      "where it would write a cold multi-GB gpui/target or src-tauri/target and fill the machine's disk.",
      "Run it through the machine's shared, warm build tree instead, from the worktree root, in the foreground:",
      "",
      `    ${command}`,
      "",
      ...(suggestion?.note ? [suggestion.note, ""] : []),
      "`cargo fmt` builds nothing and runs directly. Guard: scripts/run-worktree-cargo-guard.mjs (docs/agent-validation.md).",
    ].join("\n"),
  );
  process.exit(1);
}

/** Disk use of `dir` in MB (du counts allocated blocks, as `df` does), or 0 when it is absent. */
function sizeMb(dir) {
  if (!existsSync(dir)) return 0;
  const [kb] = execFileSync("du", ["-sk", dir], { encoding: "utf8" }).trim().split(/\s+/);
  return Math.round(Number(kb) / 1024);
}

function check() {
  const guarded = existsSync(path.join(repo, ".cargo", "config.toml")) && readFileSync(path.join(repo, ".cargo", "config.toml"), "utf8").startsWith(MARKER);
  if (!guarded && !runWorktreesDir()) return console.log("run-worktree-cargo-guard: not a no-mistakes run worktree; target sizes not checked");
  // The binaries gpui-build.mjs copies back (target/<profile>/lattice-gpui,
  // about 250 MB for release and 650 MB for debug) belong here; the rest is
  // what a local compile leaves.
  const local = (dir) => {
    const target = path.join(repo, dir);
    const copied = existsSync(target)
      ? readdirSync(target).reduce((sum, profile) => sum + sizeMb(path.join(target, profile, "lattice-gpui")), 0)
      : 0;
    return sizeMb(target) - copied;
  };
  const over = ["gpui/target", "src-tauri/target"].map((dir) => ({ dir, mb: local(dir) })).filter(({ mb }) => mb > TARGET_LIMIT_MB);
  if (!over.length) return console.log(`run-worktree-cargo-guard: gpui/target and src-tauri/target are under ${TARGET_LIMIT_MB} MB`);
  console.error(
    [
      `lattice: this no-mistakes run worktree (${repo}) holds a local cargo target over ${TARGET_LIMIT_MB} MB,`,
      "not counting the lattice-gpui binaries scripts/gpui-build.mjs copies back:",
      ...over.map(({ dir, mb }) => `    ${dir}: ${mb} MB`),
      "",
      "Something compiled here with plain cargo instead of through scripts/gpui-build.mjs; a run worktree",
      "should hold only the copied-back gpui/target/<profile>/lattice-gpui. Each such target",
      "is a cold multi-GB build, and a few runs at once fill the machine's disk. Delete it:",
      "",
      ...over.map(({ dir }) => `    rm -rf ${dir}`),
      "",
      "then run every compiling cargo command as `node scripts/gpui-build.mjs -- <cargo arguments>` from the",
      "worktree root (it puts the binary back). See docs/agent-validation.md.",
    ].join("\n"),
  );
  process.exit(1);
}

const [mode, ...rest] = process.argv.slice(2);
if (mode === "install") install();
else if (mode === "check") check();
else if (mode === "refuse" && rest.length) refuse(rest);
else {
  console.error("usage: node scripts/run-worktree-cargo-guard.mjs install | check | refuse <rustc> <args...>");
  process.exit(2);
}
