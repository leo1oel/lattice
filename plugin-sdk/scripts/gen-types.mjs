#!/usr/bin/env node
// Writes plugin-sdk/api.d.ts from plugin-api/schema/level-<N>.json, the
// plugin API's single source. `--check` fails when the file is stale instead
// of writing it. Handles exactly the JSON Schema subset schemars emits for
// lattice-core's plugin protocol (objects, tagged unions, enums, refs,
// nullable fields, string maps); anything else is an error, not a guess.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const schemaDir = join(root, "plugin-api/schema");
const out = join(root, "plugin-sdk/api.d.ts");

export function generate(schema) {
  const name = (ref) => ref.replace("#/$defs/", "");
  const doc = (text, indent = "") =>
    text ? `${indent}/** ${text.replace(/\*\//g, "*\\/").split("\n").join(`\n${indent} * `)} */\n` : "";
  const prop = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key));

  function type(s, indent) {
    if (s.$ref) return name(s.$ref);
    if (s.const !== undefined) return JSON.stringify(s.const);
    if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
    const unions = s.oneOf ?? s.anyOf;
    if (unions && !s.properties) return unions.map((u) => type(u, indent)).join(" | ");
    if (unions) return `${object(s, indent)} & (${unions.map((u) => type(u, indent)).join(" | ")})`;
    const types = [s.type].flat();
    if (types.length > 1) return types.map((t) => type({ ...s, type: t }, indent)).join(" | ");
    switch (s.type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `Array<${type(s.items, indent)}>`;
      case "object":
        return s.properties ? object(s, indent) : `Record<string, ${type(s.additionalProperties ?? {}, indent)}>`;
      case undefined:
        if (Object.keys(s).every((k) => k === "description")) return "unknown";
    }
    throw new Error(`gen-types: unsupported schema ${JSON.stringify(s).slice(0, 200)}`);
  }

  function object(s, indent) {
    const required = new Set(s.required ?? []);
    const inner = `${indent}  `;
    const lines = Object.entries(s.properties ?? {}).map(([key, value]) => {
      const optional = !required.has(key);
      return `${doc(value.description, inner)}${inner}${prop(key)}${optional ? "?" : ""}: ${type(value, inner)};`;
    });
    return `{\n${lines.join("\n")}\n${indent}}`;
  }

  const defs = Object.entries(schema.$defs)
    .map(([key, value]) => `${doc(value.description)}export type ${key} = ${type(value, "")};`)
    .join("\n\n");
  const methods = Object.entries(schema.methods)
    .map(([method, m]) => {
      const result = m.result ? type(m.result, "  ") : "void";
      return `  ${JSON.stringify(method)}: { direction: ${JSON.stringify(m.direction)}; since: ${m.since}; params: ${type(m.params, "  ")}; result: ${result} };`;
    })
    .join("\n");
  return `// Generated by plugin-sdk/scripts/gen-types.mjs from plugin-api/schema/level-${schema.apiLevel}.json.
// Do not edit; change lattice-core's plugins::protocol and regenerate.
// SPDX-License-Identifier: MIT

/** The plugin API level these types describe. */
export declare const API_LEVEL: ${schema.apiLevel};

${defs}

/** Every method, its direction, the level it arrived in, and its types. */
export interface Methods {
${methods}
}
`;
}

function main() {
  const levels = readdirSync(schemaDir)
    .map((f) => /^level-(\d+)\.json$/.exec(f)?.[1])
    .filter(Boolean)
    .map(Number)
    .sort((a, b) => b - a);
  const schema = JSON.parse(readFileSync(join(schemaDir, `level-${levels[0]}.json`), "utf8"));
  const text = generate(schema);
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error("plugin-sdk/api.d.ts is stale: run node plugin-sdk/scripts/gen-types.mjs");
      process.exit(1);
    }
    return;
  }
  writeFileSync(out, text);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
